#!/usr/bin/env python3
"""
mudshark_summary.py
===================

Turns a Mudshark "Results" Excel export (.xlsx) into a compact Summary workbook:

    TOTAL SITE CUT      <- the "Cut" operation row of the whole site
    SITE CUT ONLY       <- TOTAL SITE CUT minus TRENCH CUT
    TRENCH CUT          <- cut generated by the trench runs
    TOTAL TRENCH FILL   <- imported fill for the trench runs
    <each trench run material in UPPERCASE, e.g. CLASS 2, CLASS 3, SITE DIRT>
    TOTAL TRENCH LENGTH <- pipe / pit schedule (name, count, length)

The script is written with the PYTHON STANDARD LIBRARY ONLY.
No "pip install" is required, so it works on locked-down company laptops
with no admin rights.  All you need is Python itself (see README.md for
how to get Python without admin rights).

Usage
-----
    python mudshark_summary.py <mudshark_export.xlsx> [-o output.xlsx] [--debug]

    * <mudshark_export.xlsx> : the Excel file exported from Mudshark
    * -o output.xlsx         : optional name of the Summary file
                               (default: <input name>_SUMMARY.xlsx)
    * --debug                : also writes <input name>_DEBUG_DUMP.csv with
                               every row of every sheet (useful when you send
                               the file to someone for troubleshooting)

Windows: simply drag-and-drop the Mudshark .xlsx onto Run_Mudshark_Summary.bat

If your Mudshark export is structured differently, you can adjust the
rules in the CONFIG section just below.
"""

