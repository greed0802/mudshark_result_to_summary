def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    debug = "--debug" in argv
    if not args:
        print(__doc__)
        return 2
    input_file = args[0]
    if not os.path.isfile(input_file):
        print("ERROR: file not found: %s" % input_file)
        return 2

    output_file = None
    if "-o" in args:
        i = args.index("-o")
        try:
            output_file = args[i + 1]
        except IndexError:
            print("ERROR: -o needs a file name")
            return 2
    if not output_file:
        base, _ext = os.path.splitext(input_file)
        output_file = base + "_SUMMARY.xlsx"

    print("Reading : %s" % input_file)
    book = read_workbook(input_file)
    print("Sheets  : %s" % ", ".join(book))

    warnings = []
    data = extract(book, warnings)
    rows, merges = build_summary_rows(data)
    write_summary_xlsx(output_file, rows, merges=merges,
                       col_widths=[105, 28, 28, 28, 26, 24, 24, 24])
    print("Written : %s" % output_file)

    if warnings:
        print()
        print("*** HEADS-UP ************************************************")
        for w in warnings:
            print("  ! " + w)
        print("*************************************************************")
        write_debug_dump(os.path.splitext(input_file)[0] + "_DEBUG_DUMP.csv",
                         book)
        print("A debug dump was written next to the input file.")
    elif debug:
        dump = os.path.splitext(input_file)[0] + "_DEBUG_DUMP.csv"
        write_debug_dump(dump, book)
        print("Debug dump written: %s" % dump)

    print()
    print("Done. Open the SUMMARY file in Excel.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
