# CONFIG - adjust these if your Mudshark export uses different sheet names
# ---------------------------------------------------------------------------

# Sheet that holds the whole-site operation totals
SHEET_ALL_STRATA = "All Strata Operations"

# Sheet that holds the trench-run operation totals
SHEET_TRENCH_STRATA = "Trench Run Strata Operations"

# Sheet that lists the materials used for trench runs (bedding, backfill...)
SHEET_TRENCH_MATERIALS = "Trench Run Materials"

# Sheet that lists the trench categories / pipe & pit schedule lines
SHEET_TRENCHES = "Trenches"

# Label of the site cut operation row inside SHEET_ALL_STRATA (exact match)
CUT_ROW_LABEL = "Cut"

# A row is treated as "trenching site fill" when its label contains this word
TRENCH_SITE_HINT = "trench"

# ---------------------------------------------------------------------------
# End of CONFIG
# ---------------------------------------------------------------------------

XLSX_HEADERS = [
    "Operation Group",
    "Exported (Bulked m\u00b3)",
    "Reused (Bulked m\u00b3)",
    "Cut (Bulked m\u00b3)",
    "From Site (Compressed m\u00b3)",
    "Imported (Banked m\u00b3)",
    "Fill (Compressed m\u00b3)",
    "Site Balance (Bulked m\u00b3)",
]

TRENCHNET_RE = re.compile(
    r"^\s*TrenchNetwork\s*:\s*(.*?)\s*\((\d+)\s+(items?)\)\s*"
    r"Quantity\s+Total\s+length\s*:\s*([\d.,]+)\s*m\s*$",
    re.IGNORECASE,
)


