def _local(tag):
    """Strip the XML namespace from a tag."""
    return tag.rsplit("}", 1)[-1] if "}" in tag else tag


def _col_index(cell_ref):
    """Convert a cell reference like 'BC12' to a 1-based column index (3+26*2=55)."""
    n = 0
    for ch in cell_ref:
        if ch.isalpha():
            n = n * 26 + (ord(ch.upper()) - 64)
        else:
            break
    return n if n else None


def _read_shared_strings(zf):
    try:
        root = ET.fromstring(zf.read("xl/sharedStrings.xml"))
    except KeyError:
        return []
    strings = []
    for si in root:
        if _local(si.tag) != "si":
            continue
        # Plain <t> or rich text runs <r><t>...: join all text pieces
        text = "".join(t.text or "" for t in si.iter() if _local(t.tag) == "t")
        strings.append(text)
    return strings


def _read_sheet_list(zf):
    """Return [(sheet_name, path_inside_zip), ...] in workbook order (incl. hidden)."""
    wb = ET.fromstring(zf.read("xl/workbook.xml"))
    rels = ET.fromstring(zf.read("xl/_rels/workbook.xml.rels"))
    rid_target = {}
    for rel in rels:
        if _local(rel.tag) != "Relationship":
            continue
        target = rel.get("Target", "")
        if target.startswith("/"):
            path = target.lstrip("/")
        else:
            path = "xl/" + target
        rid_target[rel.get("Id")] = os.path.normpath(path).replace(os.sep, "/")
    sheets = []
    for el in wb.iter():
        if _local(el.tag) == "sheet":
            rid = el.get("{http://schemas.openxmlformats.org/officeDocument/"
                         "2006/relationships}id") or el.get("id")
            target = rid_target.get(rid)
            if target:
                sheets.append((el.get("name", ""), target))
    return sheets


def _read_sheet_rows(zf, path, shared):
    """Parse one sheet. Returns a list of (row_num, row_is_hidden, cells)."""
    root = ET.fromstring(zf.read(path))
    rows = []
    prev_num = 0
    for row in root.iter():
        if _local(row.tag) != "row":
            continue
        try:
            row_num = int(row.get("r"))
        except (TypeError, ValueError):
            row_num = prev_num + 1
        prev_num = row_num
        hidden = row.get("hidden") in ("1", "true")
        cells = {}
        expect_col = 1
        for c in row:
            if _local(c.tag) != "c":
                continue
            ref = c.get("r")
            col = _col_index(ref) if ref else None
            if col is None:
                col = expect_col
            expect_col = col + 1
            ctype = c.get("t")
            value = None
            if ctype == "inlineStr":
                value = "".join(t.text or "" for t in c.iter()
                                if _local(t.tag) == "t")
            else:
                raw = None
                for child in c:
                    if _local(child.tag) == "v":
                        raw = child.text
                        break
                if raw is None:
                    # formula without cached value or truly empty -> skip
                    continue
                if ctype == "s":
                    try:
                        value = shared[int(raw)]
                    except (ValueError, IndexError):
                        value = raw
                elif ctype == "str":
                    value = raw
                elif ctype == "b":
                    value = bool(int(raw))
                elif ctype == "e":
                    continue  # error cell
                else:
                    try:
                        value = float(raw)
                    except ValueError:
                        value = raw
            if value is not None and value != "":
                cells[col] = value
        rows.append((row_num, hidden, cells))
    return rows


def read_workbook(filename):
    """Read an .xlsx file -> {sheet_name: [(hidden, {col: value}), ...]}."""
    if not zipfile.is_zipfile(filename):
        raise SystemExit(
            "ERROR: '%s' is not an .xlsx file (Mudshark exports .xlsx)." % filename)
    book = {}
    with zipfile.ZipFile(filename) as zf:
        shared = _read_shared_strings(zf)
        for name, path in _read_sheet_list(zf):
            book[name] = _read_sheet_rows(zf, path, shared)
    if not book:
        raise SystemExit("ERROR: no sheets found in '%s'." % filename)
    return book


